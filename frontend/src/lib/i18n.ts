export function localize(lang: Lang, text: string): string {
  if (lang !== "hi" || !text) return text;
  return text.split(/(?<=\.) (?=[A-Z])|; /).map((part) => {
    for (const [re, to] of HI_PHRASES) { const m = part.match(re); if (m) return typeof to === "string" ? to : to(m); }
    return part;
  }).join(" ");
}
export const unitLabel = (lang: Lang, unit: string) => { const u = unit.replace("per ", ""); return lang === "hi" ? HI_UNITS[u] ?? u : u; };
